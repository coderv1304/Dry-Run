"""Generate hashed lock files from a pip resolution report.

Usage: python scripts/gen_lock.py <report.json> <output.lock>
The report comes from ``pip install --dry-run --ignore-installed --report``.
All wheel and source hashes for each resolved version are fetched from PyPI so
the lock works across platforms and CPU architectures.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path


def fetch_hashes(name: str, version: str) -> list[str]:
    """Return every sha256 hash published for one release."""
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        payload = json.load(response)
    hashes = sorted(
        {
            item["digests"]["sha256"]
            for item in payload["urls"]
            if item.get("digests", {}).get("sha256")
        }
    )
    if not hashes:
        raise SystemExit(f"no hashes for {name}=={version}")
    return hashes


def main() -> None:
    """Write a pip-compatible, fully hashed requirements file."""
    report_path, output_path = Path(sys.argv[1]), Path(sys.argv[2])
    report = json.loads(report_path.read_text(encoding="utf-8"))
    lines = [
        "# Generated by scripts/gen_lock.py. Do not edit by hand.",
        "# Install with: pip install --require-hashes -r requirements.lock",
    ]
    for item in sorted(report["install"], key=lambda row: row["metadata"]["name"].lower()):
        name = item["metadata"]["name"]
        version = item["metadata"]["version"]
        lines.append(f"{name}=={version} \\")
        hashes = fetch_hashes(name, version)
        for index, digest in enumerate(hashes):
            suffix = " \\" if index < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{suffix}")
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {output_path} ({len(report['install'])} packages)")


if __name__ == "__main__":
    main()
